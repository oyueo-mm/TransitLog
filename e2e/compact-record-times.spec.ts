import { expect, test, type Page } from '@playwright/test'
import type { Trip } from '../src/domain/types'
import { expectLayoutOk, expectNoSeriousA11y, fakeTrip, gotoApp, readDb, restoreBackup, setTime, timeOut, timeToggle } from './fixtures'

test('마지막 사용이 버스여도 빠른 기록은 지하철로 열리고 기존 버스 기록은 유지된다', async ({ page }) => {
  await gotoApp(page, 'quick')
  const modes = page.getByRole('group', { name: '교통수단', exact: true })
  await expect(modes.getByRole('button', { name: '지하철', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await modes.getByRole('button', { name: '버스', exact: true }).click()
  await page.getByLabel('버스 번호 직접 입력').fill('7000')
  await page.getByRole('button', { name: '하차 기록 없이 저장', exact: true }).click()
  await expect.poll(async () => (await readDb<Trip>(page, 'trips')).length).toBe(1)
  const before = await readDb<Trip>(page, 'trips')
  const last = (await readDb<{ key: string; value: unknown }>(page, 'settings')).find(s => s.key === 'quick.last')
  expect(before[0].mode).toBe('bus')
  expect(last?.value).toMatchObject({ mode: 'bus' })
  await gotoApp(page)
  await gotoApp(page, 'quick')
  await expect(modes.getByRole('button', { name: '지하철', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(modes.getByRole('button', { name: '지하철', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await modes.getByRole('button', { name: '버스', exact: true }).click()
  await expect(page.getByRole('button', { name: /7000/ }).first()).toBeVisible()
  await expect(page.getByLabel('버스 번호 직접 입력')).toBeVisible()
  expect(await readDb<Trip>(page, 'trips')).toEqual(before)
  expect((await readDb<{ key: string }>(page, 'settings')).find(s => s.key === 'quick.last')).toEqual(last)
})

async function pickDraft(page: Page, label: string, hour: string, minute: string) {
  const group = page.getByRole('group', { name: label, exact: true })
  for (const [part, value] of [['오전/오후', '오후'], ['시', hour], ['분', minute]]) {
    await group.getByRole('listbox', { name: `${label} ${part}`, exact: true }).getByRole('option', { name: value, exact: true }).click()
  }
}

for (const existing of [false, true]) {
  test(`${existing ? '기존 기록 수정' : '신규 기록 작성'}: 승·하차 시간은 독립적으로 펼쳐 완료하고 취소·미기록·자정 시각을 보존한다`, async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 800 })
    const trip = fakeTrip({ mode: 'bus', line: '7000', boardTime: '08:30', alightTime: '09:10' })
    if (existing) await restoreBackup(page, { trips: [trip] })
    await gotoApp(page, existing ? `trip/${trip.id}` : 'trip/new?date=2026-03-02')
    const before = await readDb<Trip>(page, 'trips')
    const board = timeToggle(page, '승차 시각')
    const alight = timeToggle(page, '하차 시각')
    await expect(board).toHaveAttribute('aria-expanded', 'false')
    await expect(alight).toHaveAttribute('aria-expanded', 'false')
    await expect(page.getByRole('listbox')).toHaveCount(0)
    await expect(timeOut(page, '승차 시각')).toHaveText(existing ? '오전 08:30' : '시간 입력 +')
    await expect(timeOut(page, '하차 시각')).toHaveText(existing ? '오전 09:10' : '시간 입력 +')
    await expectLayoutOk(page, '접힌 승·하차 시각 320px')
    await board.click()
    await pickDraft(page, '승차 시각', '9', '45')
    await alight.click()
    await pickDraft(page, '하차 시각', '10', '05')
    await expect(timeOut(page, '승차 시각')).toHaveText(existing ? '오전 08:30' : '시간 입력 +')
    await page.getByRole('button', { name: '하차 시각 완료', exact: true }).click()
    await expect(timeOut(page, '하차 시각')).toHaveText('오후 10:05')
    await expect(alight).toHaveAttribute('aria-expanded', 'false')
    await expect(board).toHaveAttribute('aria-expanded', 'true')
    await page.getByRole('button', { name: '승차 시각 취소', exact: true }).click()
    await expect(timeOut(page, '승차 시각')).toHaveText(existing ? '오전 08:30' : '시간 입력 +')
    expect(await readDb<Trip>(page, 'trips')).toEqual(before)
    await setTime(page, '승차 시각', '23:59')
    await alight.click()
    await page.getByRole('group', { name: '하차 시각', exact: true }).getByRole('button', { name: '지우기', exact: true }).click()
    await page.getByRole('button', { name: '하차 시각 완료', exact: true }).click()
    await expect(timeOut(page, '하차 시각')).toHaveText('시간 입력 +')
    await expect(timeOut(page, '승차 시각')).toHaveText('오후 11:59')
    await setTime(page, '하차 시각', '00:10')
    await expect(page.getByRole('listbox')).toHaveCount(0)
    await expectNoSeriousA11y(page, '접힌 기록 시간 편집')
    await page.screenshot({ path: `test-results/screens/compact-times-${existing ? 'edit' : 'new'}-320.png`, fullPage: true })
    await page.getByRole('button', { name: '저장', exact: true }).click()
    await expect(page.getByRole('heading', { name: /3월 2일/ })).toBeVisible()
    const [saved] = await readDb<Trip>(page, 'trips')
    expect(saved).toMatchObject({ boardTime: '23:59', alightTime: '00:10', mode: existing ? 'bus' : 'subway' })
    await gotoApp(page, `trip/${saved.id}`)
    await expect(timeOut(page, '승차 시각')).toHaveText('오후 11:59')
    await expect(timeOut(page, '하차 시각')).toHaveText('오전 12:10')
    await expect(page.getByRole('listbox')).toHaveCount(0)
  })
}
